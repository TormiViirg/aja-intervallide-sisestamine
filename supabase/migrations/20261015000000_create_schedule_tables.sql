create table public.app_config (
  id text primary key check (id = 'default'),
  allowed_range jsonb not null,
  opening_times jsonb not null
);

create table public.teams (
  id text primary key,
  name text not null
);

create table public.volunteers (
  id bigint generated by default as identity primary key,
  name text not null,
  festival text not null,
  team text not null references public.teams(id),
  location text not null,
  opened jsonb not null default '[]'::jsonb
);
create index volunteers_festival_team_idx on public.volunteers (festival, team);

create table public.drafts (
  team_id text primary key references public.teams(id) on delete cascade,
  schedule jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.publications (
  id bigint generated by default as identity primary key,
  team_id text not null references public.teams(id) on delete cascade,
  schedule jsonb not null,
  publish_at timestamptz not null,
  status text not null check (status in ('published', 'scheduled')),
  created_at timestamptz not null default now()
);
create index publications_team_publish_at_idx on public.publications (team_id, publish_at desc);

alter table public.app_config enable row level security;
alter table public.teams enable row level security;
alter table public.volunteers enable row level security;
alter table public.drafts enable row level security;
alter table public.publications enable row level security;